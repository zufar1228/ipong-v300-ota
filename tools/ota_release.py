#!/usr/bin/env python3
"""Sign and publish an iPong OTA release.

Usage:
  python tools/ota_release.py keygen     # one time: create signing key + src/ota_pubkey.h
  python tools/ota_release.py release    # after `pio run`: sign build, write firmware/ + version.json

The ESP32 only installs a firmware whose ECDSA P-256 signature over
"<version>|<size>|<sha256 hex>" verifies against the public key compiled
into the running firmware. Keep keys/ota_private.pem secret and backed up:
if it is lost, devices in the field can only be updated over USB.

Requires: pip install cryptography
"""
import argparse
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

ROOT = Path(__file__).resolve().parent.parent
PRIV_KEY = ROOT / "keys" / "ota_private.pem"
PUB_HEADER = ROOT / "src" / "ota_pubkey.h"
MAIN_CPP = ROOT / "src" / "main.cpp"
BUILD_BIN = ROOT / ".pio" / "build" / "esp32doit-devkit-v1" / "firmware.bin"
OUT_BIN = ROOT / "firmware" / "firmware.bin"
OUT_JSON = ROOT / "firmware" / "version.json"
BIN_URL = "https://raw.githubusercontent.com/zufar1228/ipong-v300-ota/main/firmware/firmware.bin"

SEMVER = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")


def parse_ver(v):
    m = SEMVER.match(v or "")
    if not m:
        sys.exit(f"Invalid version '{v}', expected X.Y.Z")
    return tuple(int(x) for x in m.groups())


def public_pem(pub):
    return pub.public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
    ).decode()


def write_pub_header(pub):
    PUB_HEADER.write_text(
        "#pragma once\n"
        "// Generated by tools/ota_release.py keygen. Public key that verifies OTA firmware signatures.\n"
        "// Safe to commit. The matching private key lives in keys/ota_private.pem (never commit it).\n"
        f'static const char OTA_PUBKEY_PEM[] = R"PEM(\n{public_pem(pub)})PEM";\n',
        encoding="utf-8",
    )


def load_key():
    if not PRIV_KEY.exists():
        sys.exit(f"{PRIV_KEY} not found. Run: python tools/ota_release.py keygen")
    return serialization.load_pem_private_key(PRIV_KEY.read_bytes(), password=None)


def keygen(force):
    if PRIV_KEY.exists() and not force:
        sys.exit(
            f"{PRIV_KEY} already exists. Use --force only if you accept that devices running the "
            "current firmware will REJECT updates signed with a new key (USB flash needed)."
        )
    key = ec.generate_private_key(ec.SECP256R1())
    PRIV_KEY.parent.mkdir(exist_ok=True)
    PRIV_KEY.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    write_pub_header(key.public_key())
    print(f"Private key: {PRIV_KEY}  (BACK THIS UP, never commit)")
    print(f"Public key header: {PUB_HEADER}")


def release():
    key = load_key()
    if public_pem(key.public_key()) not in PUB_HEADER.read_text(encoding="utf-8"):
        sys.exit("src/ota_pubkey.h does not match keys/ota_private.pem. Refusing to sign.")

    m = re.search(r'#define\s+FW_VERSION\s+"([^"]+)"', MAIN_CPP.read_text(encoding="utf-8"))
    if not m:
        sys.exit("FW_VERSION not found in src/main.cpp")
    version = m.group(1)
    new_ver = parse_ver(version)

    if OUT_JSON.exists():
        try:
            old = json.loads(OUT_JSON.read_text(encoding="utf-8")).get("version", "0.0.0")
            if new_ver <= parse_ver(old):
                sys.exit(f"FW_VERSION {version} must be greater than published {old}. Bump it in src/main.cpp.")
        except json.JSONDecodeError:
            pass

    if not BUILD_BIN.exists():
        sys.exit(f"{BUILD_BIN} not found. Run `pio run` first.")
    if BUILD_BIN.stat().st_mtime < MAIN_CPP.stat().st_mtime:
        sys.exit("firmware.bin is older than src/main.cpp. Run `pio run` again.")

    data = BUILD_BIN.read_bytes()
    if not data or data[0] != 0xE9:
        sys.exit("firmware.bin is not a valid ESP32 app image (magic 0xE9 missing).")
    if f'"{version}"'.encode() not in data and version.encode() not in data:
        sys.exit(f"Version string {version} not found inside firmware.bin. Stale build?")

    sha = hashlib.sha256(data).hexdigest()
    message = f"{version}|{len(data)}|{sha}".encode()
    sig = key.sign(message, ec.ECDSA(hashes.SHA256())).hex()

    shutil.copyfile(BUILD_BIN, OUT_BIN)
    OUT_JSON.write_text(
        json.dumps(
            {"version": version, "url": BIN_URL, "size": len(data), "sha256": sha, "sig": sig},
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"Release v{version}: {len(data)} bytes, sha256 {sha}")
    print("Now: git add firmware/ src/ && git commit -m \"Release v%s\" && git push" % version)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    kg = sub.add_parser("keygen", help="create signing key pair")
    kg.add_argument("--force", action="store_true")
    sub.add_parser("release", help="sign build output and write firmware/version.json")
    args = ap.parse_args()
    if args.cmd == "keygen":
        keygen(args.force)
    else:
        release()


if __name__ == "__main__":
    main()
