#!/usr/bin/env python3
"""Generate the app icons: PWA icons embedded as C arrays in src/web_icons.h,
plus the Android launcher icons in android/app/src/main/res/mipmap-*/.

Usage: python tools/make_icons.py   (requires: pip install pillow)
"""
import io
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "web_icons.h"
ANDROID_RES = ROOT / "android" / "app" / "src" / "main" / "res"
ANDROID_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
SS = 4  # supersampling for smooth edges


def draw_icon(size, maskable):
    s = size * SS
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if maskable:
        d.rectangle([0, 0, s, s], fill=(18, 64, 122))
    else:
        d.rounded_rectangle([0, 0, s - 1, s - 1], radius=int(s * 0.22), fill=(18, 64, 122))
    # Table line + net
    d.rectangle([0, int(s * 0.49), s, int(s * 0.51)], fill=(255, 255, 255, 60))
    # Keep the artwork inside the maskable safe zone (inner 80%)
    k = 0.78 if maskable else 0.9
    o = s * (1 - k) / 2

    def P(x, y):
        return o + x * s * k, o + y * s * k

    # Handle
    hx, hy = P(0.58, 0.60)
    hx2, hy2 = P(0.80, 0.84)
    hw = int(s * k * 0.17)
    d.line([hx, hy, hx2, hy2], fill=(139, 90, 43), width=hw)
    d.ellipse([hx2 - hw / 2, hy2 - hw / 2, hx2 + hw / 2, hy2 + hw / 2], fill=(139, 90, 43))
    # Paddle blade (red rubber, black edge)
    cx, cy = P(0.40, 0.42)
    r = s * k * 0.33
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(17, 17, 17))
    r2 = r * 0.9
    d.ellipse([cx - r2, cy - r2, cx + r2, cy + r2], fill=(226, 58, 58))
    # Ball
    bx, by = P(0.80, 0.18)
    br = s * k * 0.12
    d.ellipse([bx - br, by - br, bx + br, by + br], fill=(255, 138, 31))
    hr = br * 0.35
    d.ellipse([bx - br * 0.45 - hr, by - br * 0.45 - hr, bx - br * 0.45 + hr, by - br * 0.45 + hr],
              fill=(255, 220, 170))
    img = img.resize((size, size), Image.LANCZOS).quantize(colors=48, method=Image.FASTOCTREE)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    icons = {
        "ICON_192": draw_icon(192, False),
        "ICON_512": draw_icon(512, False),
        "ICON_MASK_512": draw_icon(512, True),
        "ICON_APPLE_180": draw_icon(180, True),
    }
    parts = ["#pragma once\n// Generated by tools/make_icons.py. Do not edit by hand.\n#include <Arduino.h>\n"]
    for name, data in icons.items():
        parts.append(c_array(name, data))
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(", ".join(f"{k}={len(v)}B" for k, v in icons.items()))
    for dpi, px in ANDROID_SIZES.items():
        d = ANDROID_RES / f"mipmap-{dpi}"
        d.mkdir(parents=True, exist_ok=True)
        (d / "ic_launcher.png").write_bytes(draw_icon(px, False))
    print("Android launcher icons written")


if __name__ == "__main__":
    main()
